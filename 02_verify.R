suppressPackageStartupMessages(library(tidyverse))
if (Sys.getenv("TED_VERIFY", "0") != "1") { cat("Verification against the published numbers skipped (set TED_VERIFY=1 when running on the registry data)\n"); quit(save = "no") }
source("00_helpers.R"); source("00_firth.R"); d <- readRDS("outputs/ted_analytic.rds")

chk <- function(label, value, expected) cat(sprintf("%-55s %-12s expected %-12s %s\n", label, as.character(value), as.character(expected),
                                                     ifelse(identical(as.character(value), as.character(expected)), "OK", "<<< MISMATCH")))
chk("N", nrow(d), 147)
chk("Centres", paste(table(d$centre), collapse = "/"), "42/34/34/29/8")
chk("Activity classifiable", sum(!is.na(d$activity)), 139)
chk("Active at baseline", sum(d$activity == "Active", na.rm = TRUE), 65)
chk("Any follow-up", sum(d$has_followup), 124)
chk("Paired activity", sum(d$paired_activity), 109)
chk("Paired CAS", sum(!is.na(d$cas) & !is.na(d$cas_fu)), 93)
chk("Active at baseline among paired", sum(d$paired_activity & d$activity == "Active"), 51)
chk("Active at last visit among paired", sum(d$paired_activity & d$activity_fu == "Active"), 14)
chk("Inactivated", sum(d$inactivated == 1, na.rm = TRUE), 37)
chk("New DON / evaluable", paste(sum(d$new_don == "Yes", na.rm = TRUE), sum(!is.na(d$new_don)), sep = "/"), "3/107")
chk("DON baseline", paste(sum(d$don == "Yes", na.rm = TRUE), sum(!is.na(d$don)), sep = "/"), "10/145")
chk("Sight-threatening", sum(d$sev4 == "Sight-threatening (DON/corneal breakdown)"), 12)
chk("Moderate-to-severe", sum(d$sev4 == "Moderate-to-severe"), 64)
chk("Mild incomplete", sum(d$sev4 == "Mild features, incomplete assessment"), 60)
chk("IVMP (administered or planned)", sum(d$gc_iv == "Yes"), 59)
chk("Any systemic GC", sum(d$gc_any == "Yes"), 83)
chk("Oral only", sum(d$gc_oral_only == "Yes"), 24)
chk("Surgery", sum(d$orbital_surgery == "Yes"), 36)
chk("Second line", sum(d$second_line == "Yes"), 13)
chk("Months symptom onset to last visit (median)", med_iqr(d$months_go_to_fu), "28.0 (11.1–62.0)")
chk("Exo missing", sum(is.na(d$exo_max)), 92)
chk("TRAb missing", sum(is.na(d$trab_status)), 108)
chk("CAS missing", sum(is.na(d$cas)), 30)
chk("Unfavourable", paste(sum(d$unfavourable == "Yes", na.rm = TRUE), sum(!is.na(d$unfavourable)), sep = "/"), "7/113")
chk("Mean delta CAS", round(mean(d$delta_cas, na.rm = TRUE), 2), -1.35)

cat("\nFirth primary model (expected age OR 1.39 [1.06–1.86], male 2.16 [0.93–5.17], smoking 1.22 [0.36–4.32], RAI 0.58 [0.18–1.79]):\n")
dd <- drop_na(d, y_active, age10, male, current_smoker, rai)
f_prim <- firth_fit(y_active ~ age10 + male + current_smoker + rai, dd)
print(tidy_firth(f_prim, "Primary") |> mutate(across(c(OR, lo, hi), ~ round(.x, 2)), p = fmt_p(p)))
cat("\nCentre-adjusted (expected age OR 1.21 [0.90–1.66]):\n")
f_cent <- firth_fit(y_active ~ age10 + male + current_smoker + rai + centre, dd)
print(tidy_firth(f_cent, "Centre") |> filter(!str_detect(term, "centre")) |> mutate(across(c(OR, lo, hi), ~ round(.x, 2)), p = fmt_p(p)))
